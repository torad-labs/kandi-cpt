#!/usr/bin/env python3
"""Build an SFT (instruction-tuning) dataset that turns the CPT-installed associations into conversational
retrieval. Festival-agnostic: iterates every edition's 15_structured + festival_meta, so it covers EDC now
and any other festival once its data lands.

The CPT model HAS the facts (forced-choice evals prove it) but can't yet ANSWER a question — that's the SFT
job. We format grounded Q/A in the Gemma chat template and mask the loss to the assistant turn only:

    <bos><start_of_turn>user\n{Q}<end_of_turn>\n<start_of_turn>model\n{A}<end_of_turn>
    labels = -100 over the prompt, real token ids over "{A}<end_of_turn>", -100 over right-padding.

Sources, all grounded (no invention):
  • edition→venue   (festival_meta.venue)
  • artist→stage    (plays_at triples whose object is :stage:)
  • artist→day      (plays_at attrs.day)
  • artist→edition  (plays_at triples — which edition an artist played)
  • the QA-form lines already in 25_hydrated ("Q: … A: …"), parsed into (q,a) for phrasing diversity

    PYTHONPATH=scripts python scripts/build_sft.py [--editions …] [--seq-len 256]
        [--max-per-relation 6] [--out sft_v1]
Output: data/_build/30_tokenized/<out>.arrow (columns input_ids + labels) + <out>_stats.json.
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from collections import Counter

from transformers import AutoTokenizer
from datasets import Dataset

import config as C
from pipeline.editions import iter_editions
from pipeline import fact_expand as FE

QA_LINE = re.compile(r"^\s*Q:\s*(.+?)\s*A:\s*(.+?)\s*$", re.I | re.S)


def edition_qas(ed, max_per_rel: int) -> list[tuple[str, str]]:
    """Grounded (Q, A) pairs for one edition, from its festival_meta + 15_structured triples/entities."""
    meta_p = ed.dir / "festival_meta.json"
    if not meta_p.exists():
        return []
    meta = json.loads(meta_p.read_text())
    name = meta.get("name") or ed.slug
    venue = (meta.get("venue") or "").strip()
    struct = ed.dir / "15_structured"
    tri_p, ent_p = struct / "triples.jsonl", struct / "entities.jsonl"
    if not tri_p.exists():
        return []
    ents = {}
    if ent_p.exists():
        for l in ent_p.read_text(encoding="utf-8", errors="replace").splitlines():
            if l.strip():
                try:
                    o = json.loads(l); ents[o["id"]] = o.get("name_canonical", "")
                except Exception:
                    pass
    qas: list[tuple[str, str]] = []
    by_rel: Counter = Counter()
    if venue and not venue.lower().startswith("various"):
        qas.append((f"Where is {name} held?", f"{name} is held at {venue}."))
        qas.append((f"What venue hosts {name}?", f"{name} takes place at {venue}."))

    seen_ed_artist = set()
    for l in tri_p.read_text(encoding="utf-8", errors="replace").splitlines():
        if not l.strip():
            continue
        try:
            t = json.loads(l)
        except Exception:
            continue
        if t.get("predicate") != "plays_at":
            continue
        a = ents.get(t.get("subject_id"), "").strip()
        if not a or len(a) < 2:
            continue
        obj = str(t.get("object", ""))
        day = (t.get("attrs") or {}).get("day", "")
        if ":stage:" in obj and by_rel["stage"] < max_per_rel:
            stage = FE.spaced(obj.split(":stage:")[1])
            qas.append((f"Which stage does {a} play at {name}?",
                        f"{a} plays the {stage} stage at {name}."))
            by_rel["stage"] += 1
            if day and by_rel["day"] < max_per_rel:
                qas.append((f"On which day does {a} perform at {name}?",
                            f"{a} performs on {day} at {name}."))
                by_rel["day"] += 1
        elif ":festival:" in obj and a not in seen_ed_artist and by_rel["edition"] < max_per_rel * 3:
            qas.append((f"At which EDC edition did {a} perform?", f"{a} performed at {name}."))
            seen_ed_artist.add(a); by_rel["edition"] += 1

    # diverse phrasings already generated by the hydration engine
    hyd = ed.dir / "25_hydrated/relations.jsonl"
    if hyd.exists():
        n = 0
        for l in hyd.read_text(encoding="utf-8", errors="replace").splitlines():
            if n >= max_per_rel * 2 or not l.strip():
                continue
            try:
                txt = json.loads(l).get("text", "")
            except Exception:
                continue
            m = QA_LINE.match(txt)
            if m and len(m.group(2)) < 200:
                qas.append((m.group(1).strip(), m.group(2).strip()))
                n += 1
    return qas


def encode(tok, q: str, a: str, seq_len: int):
    """Gemma chat turn, assistant-only label mask, right-padded to seq_len. Returns (ids, labels) or None."""
    bos = tok.bos_token or ""
    prompt = f"{bos}<start_of_turn>user\n{q}<end_of_turn>\n<start_of_turn>model\n"
    ans = f"{a}<end_of_turn>"
    p = tok(prompt, add_special_tokens=False).input_ids
    aw = tok(ans, add_special_tokens=False).input_ids
    ids = p + aw
    labels = [-100] * len(p) + list(aw)
    if len(ids) > seq_len:
        return None                                   # QA longer than the window — skip (rare; keeps masking clean)
    pad = tok.pad_token_id if tok.pad_token_id is not None else tok.eos_token_id
    k = seq_len - len(ids)
    return ids + [pad] * k, labels + [-100] * k


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--editions", help="restrict to 'city/year,…' (default: all)")
    ap.add_argument("--seq-len", type=int, default=256)
    ap.add_argument("--max-per-relation", type=int, default=6, help="cap Q/A per relation per edition (balance)")
    ap.add_argument("--out", default="sft_v1")
    args = ap.parse_args()

    tok = AutoTokenizer.from_pretrained(str(C.MODEL_PATH), use_fast=True)
    pairs: list[tuple[str, str]] = []
    n_ed = 0
    for ed in iter_editions("edc", only=args.editions):
        qa = edition_qas(ed, args.max_per_relation)
        if qa:
            pairs.extend(qa); n_ed += 1
    # dedup identical (q,a), shuffle
    pairs = list(dict.fromkeys(pairs))
    random.seed(0); random.shuffle(pairs)
    if not pairs:
        sys.exit("no Q/A pairs built (need 15_structured + festival_meta)")

    rows_ids, rows_lab = [], []
    skipped = 0
    for q, a in pairs:
        enc = encode(tok, q, a, args.seq_len)
        if enc is None:
            skipped += 1; continue
        rows_ids.append(enc[0]); rows_lab.append(enc[1])
    supervised = sum(1 for lab in rows_lab for x in lab if x != -100)

    OUT = C.TOKENIZED_DIR
    OUT.mkdir(parents=True, exist_ok=True)
    Dataset.from_dict({"input_ids": rows_ids, "labels": rows_lab}).save_to_disk(str(OUT / f"{args.out}.arrow"))
    stats = {"examples": len(rows_ids), "editions": n_ed, "seq_len": args.seq_len,
             "supervised_tokens": supervised, "skipped_too_long": skipped,
             "tokens_total": len(rows_ids) * args.seq_len, "editions_filter": args.editions or "all"}
    (OUT / f"{args.out}_stats.json").write_text(json.dumps(stats, indent=2))
    print(f"SFT: {len(rows_ids)} examples from {n_ed} editions | supervised tokens={supervised:,} "
          f"| skipped(too long)={skipped} | seq_len={args.seq_len}")
    print(f"  sample Q/A: {pairs[0][0]!r} -> {pairs[0][1]!r}")
    print(f"saved {OUT / (args.out + '.arrow')}")


if __name__ == "__main__":
    main()
