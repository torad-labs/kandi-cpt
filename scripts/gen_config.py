"""The config-generator primitive. Sweeps and chain-scripts use THIS to vary a run — they write a resolved,
validated config file and launch the ONE entrypoint with it, instead of passing behavior flags to the trainer
(flags no longer exist; see docs/CONFIG_AUDIT.md + AGENTS.md).

  python scripts/gen_config.py --base configs/sft_edc.yaml --out /tmp/run.yaml --mode sft \\
      --set data.tokenized=data/_build/30_tokenized/sft_v9.arrow \\
            run.save_dir=checkpoints/sft/edc_sft_v9 \\
            data.init_from=checkpoints/cpt/edc_all97_v1

Each --set is dotted `section.key=value` (value parsed as a YAML scalar → correct int/float/bool/null/str).
The result is validated through CptConfig before writing, so a bad sweep value fails HERE, not 3000 steps in.
Prints the output path + fingerprint.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cpt_config import CptConfig  # noqa: E402


def _set_dotted(d: dict, dotted: str, value) -> None:
    parts = dotted.split(".")
    node = d
    for p in parts[:-1]:
        node = node.setdefault(p, {})
        if not isinstance(node, dict):
            raise SystemExit(f"--set {dotted}: '{p}' is not a mapping in the base config")
    node[parts[-1]] = value


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", required=True, help="base config to derive from")
    ap.add_argument("--out", required=True, help="where to write the generated config")
    ap.add_argument("--mode", choices=["cpt", "sft"], default=None)
    ap.add_argument("--set", dest="overrides", nargs="*", default=[],
                    help="dotted section.key=value overrides (value parsed as a YAML scalar)")
    args = ap.parse_args()

    raw = yaml.safe_load(Path(args.base).read_text()) or {}
    if args.mode:
        raw["mode"] = args.mode
    for ov in args.overrides:
        if "=" not in ov:
            raise SystemExit(f"--set expects key=value, got '{ov}'")
        key, _, val = ov.partition("=")
        _set_dotted(raw, key.strip(), yaml.safe_load(val))   # YAML scalar → int/float/bool/null/str
    # validate through the contract (structural + cross-field) before writing — fail loud HERE
    cfg = CptConfig._from_dict(raw)
    cfg.validate()
    Path(args.out).write_text(
        "# GENERATED by scripts/gen_config.py — do not hand-edit; regenerate from --base + --set.\n"
        f"# base: {args.base}\n" + yaml.safe_dump(raw, sort_keys=False, default_flow_style=False, width=100))
    print(f"wrote {args.out}  (mode={cfg.mode}, fingerprint={cfg.fingerprint()})")


if __name__ == "__main__":
    main()
